function validateArticles() {
  const errors = []
  const slugs = new Set()
  const titles = new Set()

  for (const article of articles) {
    if (!/^[a-z0-9-]+$/.test(article.slug)) errors.push(`${article.slug}: slug 格式错误`)
    if (slugs.has(article.slug)) errors.push(`${article.slug}: slug 重复`)
    if (titles.has(article.title)) errors.push(`${article.title}: 标题重复`)
    if (article.summary.length < 35 || article.summary.length > 120) {
      errors.push(`${article.title}: 摘要长度应为 35-120 字`)
    }
    if (article.content.length < 500) errors.push(`${article.title}: 正文少于 500 字`)
    if ((article.content.match(/^## /gm) ?? []).length < 3) {
      errors.push(`${article.title}: 正文至少需要 3 个二级标题`)
    }
    if (!Array.isArray(article.tags) || article.tags.length < 2) {
      errors.push(`${article.title}: 至少需要 2 个标签`)
    }
    slugs.add(article.slug)
    titles.add(article.title)
  }

  for (const category of Object.keys(categoryNames)) {
    const count = articles.filter((article) => article.category === category).length
    if (count < 10) errors.push(`${categoryNames[category]}只有 ${count} 篇，至少需要 10 篇`)
  }

  if (errors.length > 0) throw new Error(`内容校验失败：\n- ${errors.join('\n- ')}`)
}

async function main() {
  validateArticles()

  const apply = process.argv.includes('--apply')
  const env = loadEnv()
  if (!env.NEXT_PUBLIC_SUPABASE_URL || !env.SUPABASE_SERVICE_ROLE_KEY) {
    throw new Error('.env.local 缺少 Supabase 服务地址或服务端密钥')
  }

  const supabase = createClient(
    env.NEXT_PUBLIC_SUPABASE_URL,
    env.SUPABASE_SERVICE_ROLE_KEY,
    { auth: { persistSession: false, autoRefreshToken: false } }
  )

  const { data: existing, error: queryError } = await supabase
    .from('articles')
    .select('slug')
    .in('slug', articles.map((article) => article.slug))

  if (queryError) throw queryError

  const existingSlugs = new Set((existing ?? []).map((article) => article.slug))
  const pending = articles.filter((article) => !existingSlugs.has(article.slug))

  console.log('内容校验通过：')
  for (const [category, label] of Object.entries(categoryNames)) {
    const total = articles.filter((article) => article.category === category).length
    const add = pending.filter((article) => article.category === category).length
    console.log(`  ${label}: ${total} 篇（本次新增 ${add} 篇）`)
  }
  console.log(`  已存在并跳过: ${articles.length - pending.length} 篇`)

  if (!apply) {
    console.log('\n预览模式，未写入数据库。使用 --apply 正式发布。')
    return
  }

  if (pending.length > 0) {
    const publishedAt = new Date().toISOString()
    const rows = pending.map((article, index) => ({
      ...article,
      status: 'published',
      published_at: publishedAt,
      sort_order: 100 - index,
    }))

    const { error: insertError } = await supabase.from('articles').insert(rows)
    if (insertError) throw insertError
  }

  const { data: counts, error: countError } = await supabase
    .from('articles')
    .select('category')
    .eq('status', 'published')
    .in('category', Object.keys(categoryNames))

  if (countError) throw countError

  console.log('\n发布完成，线上已发布数量：')
  for (const [category, label] of Object.entries(categoryNames)) {
    const count = (counts ?? []).filter((article) => article.category === category).length
    console.log(`  ${label}: ${count} 篇`)
  }
}

